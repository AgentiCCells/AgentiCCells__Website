// Derives every role's agent behaviour policy from board/abp/inputs.json.
// The gap is computed, never written by hand (https://abp.sgit.ai/model/delta/index.md):
//   excess            = granted primitives not in the mandate
//   unbounded_excess  = excess whose barrier is not a boundary
//   shortfall         = mandated primitives not granted
//   wider_than_asked  = mandated primitives the grant holds at a wider instance (host, tenant or world reach)
// Writes data/abp.json and board/abp/<role>.md.
// Usage: node board/abp/derive.mjs          write the outputs
//        node board/abp/derive.mjs --check  recompute and fail if a stored output disagrees
// Node built-ins only. Written by abp@agenticcells.dinis, 2026-11-15.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const COMPUTED_BY = 'board/abp/derive.mjs v1';
const input = JSON.parse(readFileSync(join(here, 'inputs.json'), 'utf8'));
const version = (x) => 'sha256:' + createHash('sha256').update(JSON.stringify(x)).digest('hex').slice(0, 12);

const grant = input.grant;
const byName = Object.fromEntries(grant.map((g) => [g.primitive, g]));
const granted = grant.filter((g) => g.granted);
const wide = new Set(['host', 'tenant', 'world']);
const grantVersion = version(grant);

function derive(role) {
  const mandate = [...input.common_mandate.items, ...role.extra];
  for (const m of mandate) if (!byName[m.primitive]) throw new Error(`${role.role}: unknown primitive ${m.primitive}`);
  const asked = new Set(mandate.map((m) => m.primitive));
  const excess = granted.filter((g) => !asked.has(g.primitive));
  return {
    role: role.role,
    agent: role.agent,
    asked: role.asked,
    mandate_source: role.mandate_source,
    may_not: role.may_not.map((text) => ({ text, barrier: 'expectation' })),
    mandate,
    delta: {
      grant_version: grantVersion,
      mandate_version: version(mandate),
      pack_version: input.vocabulary.source_version,
      computed_by: COMPUTED_BY,
      excess: excess.map((g) => g.primitive),
      unbounded_excess: excess.filter((g) => g.barrier !== 'boundary').map((g) => g.primitive),
      shortfall: [...asked].filter((p) => !byName[p].granted),
      wider_than_asked: [...asked].filter((p) => byName[p].granted && wide.has(byName[p].reach)),
      irreversible_excess: excess.filter((g) => g.undo === 'no').map((g) => g.primitive),
    },
  };
}

const roles = input.roles.map(derive);
const data = {
  about: 'Agent behaviour policies for the AgentiCCells team: what each role can reach (grant, measured), what it was asked to do (mandate, from its brief), and the derived gap with the barrier on each capability. Derived by board/abp/derive.mjs from board/abp/inputs.json; never edit by hand. No score and no verdict.',
  licence: 'CC BY 4.0',
  as_at: input.deployment.as_at,
  deployment: input.deployment,
  barrier_kinds: input.barriers.kinds,
  grant,
  roles,
};
const dataText = JSON.stringify(data, null, 2) + '\n';

const cell = (s) => String(s).replace(/\|/g, '/').replace(/\n/g, ' ');
function page(r) {
  const L = [];
  const d = r.delta;
  L.push(`# Agent behaviour policy: ${r.agent}`, '');
  L.push(`Derived by \`${COMPUTED_BY}\` from \`board/abp/inputs.json\`. Do not edit this file; change the grant or the mandate and run the script. As at ${input.deployment.as_at}. Grant ${d.grant_version}, mandate ${d.mandate_version}, vocabulary ${d.pack_version}.`, '');
  L.push(`Deployment: ${input.deployment.shape} Grant measured by ${input.deployment.measured_by}.`, '');
  L.push('## Label', '', '| Field | Value |', '|---|---|');
  L.push(`| Grant | ${granted.length} of ${grant.length} primitives |`);
  L.push(`| Mandate | ${new Set(r.mandate.map((m) => m.primitive)).size} primitives |`);
  L.push(`| Excess | ${d.excess.length} |`);
  L.push(`| Unbounded excess | ${d.unbounded_excess.length} |`);
  L.push(`| Irreversible excess | ${d.irreversible_excess.length} |`);
  L.push(`| Shortfall | ${d.shortfall.length} |`);
  L.push(`| Mandated but granted wider than asked | ${d.wider_than_asked.length} |`);
  L.push(`| Widest reach | ${granted.some((g) => g.reach === 'world') ? 'world' : 'tenant'} |`);
  L.push(`| Measured rows | ${grant.filter((g) => g.tier === 'measured').length} of ${grant.length}, the rest derived |`, '');
  L.push('## Mandate (what it was asked to do)', '', r.asked, '', `Source: ${r.mandate_source}.`, '');
  L.push('| verb.object.reach | Instance |', '|---|---|');
  for (const m of r.mandate) L.push(`| \`${m.primitive}\` | ${cell(m.instance)} |`);
  L.push('', '## Gap (reach minus mandate), with the barrier on each', '');
  L.push('| verb.object.reach | Undo | What it reaches here | Barrier | Bounds anything | Note |', '|---|---|---|---|---|---|');
  for (const p of d.excess) {
    const g = byName[p];
    L.push(`| \`${p}\` | ${g.undo} | ${cell(g.instance)} | ${g.barrier} | ${g.barrier === 'boundary' ? 'yes' : 'no'} | ${cell(g.barrier_note || g.evidence)} |`);
  }
  if (d.wider_than_asked.length) {
    L.push('', '## Asked for, but reachable much wider', '', 'These are in the mandate, so they are not excess by primitive, but the grant holds them at a wider instance than the brief asks.', '');
    L.push('| verb.object.reach | Asked | Reachable | Barrier |', '|---|---|---|---|');
    for (const p of d.wider_than_asked) {
      const m = r.mandate.filter((x) => x.primitive === p).map((x) => x.instance).join('; ');
      L.push(`| \`${p}\` | ${cell(m)} | ${cell(byName[p].instance)} | ${byName[p].barrier} |`);
    }
  }
  if (d.shortfall.length) {
    L.push('', '## Shortfall (asked for, not reachable)', '');
    for (const p of d.shortfall) L.push(`- \`${p}\`: ${cell(byName[p].instance)}`);
  }
  L.push('', '## May not, with its barrier', '', 'Each line comes from the brief or the roster. No boundary stands behind any of them today, so each is an expectation: a rule in prose, enforced by nobody (https://abp.sgit.ai/model/barriers/index.md).', '');
  for (const m of r.may_not) L.push(`- ${m.text}: **${m.barrier}**`);
  L.push('', '## Full reach', '', 'The same grant for every role, because every agent runs in the one container. Tier says whether the row was seen (measured) or reasoned from the setup (derived).', '');
  L.push('| verb.object.reach | Reach | Undo | Granted | Tier | Barrier |', '|---|---|---|---|---|---|');
  for (const g of grant) L.push(`| \`${g.primitive}\` | ${g.reach} | ${g.undo} | ${g.granted ? 'yes' : 'no'} | ${g.tier} | ${g.barrier} |`);
  L.push('', 'Licence: CC BY 4.0. Vocabulary: https://abp.sgit.ai/model/capabilities/index.md (from https://what-can-it-do.games.sgit.ai/map/index.html).', '');
  return L.join('\n');
}

const outputs = [[join(root, 'data', 'abp.json'), dataText], ...roles.map((r) => [join(here, `${r.role}.md`), page(r)])];
if (process.argv.includes('--check')) {
  const bad = outputs.filter(([p, t]) => !existsSync(p) || readFileSync(p, 'utf8') !== t).map(([p]) => p.slice(root.length + 1));
  if (bad.length) { console.error('stored policy disagrees with a recompute:\n' + bad.join('\n')); process.exit(1); }
  console.log('OK');
} else {
  for (const [p, t] of outputs) writeFileSync(p, t);
  console.log(`derived ${roles.length} policies into data/abp.json and board/abp/`);
}
