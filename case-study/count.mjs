// Counts for the case study, generated from git, team/activity and team/costs.jsonl. Nothing here is typed by hand.
// Usage: node case-study/count.mjs          prints case-study/numbers.md to stdout
//        node case-study/count.mjs --write  writes case-study/numbers.md
// Written by reporter@AgentiCCells.dinis, 2026-11-15 (R3).
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
const git = (...a) => execFileSync('git', a, { encoding: 'utf8', maxBuffer: 1 << 26 });
const roleOf = (s) => String(s || '').toLowerCase().replace(/@agenticcells\.dinis$/, '').replace(/@agenticcells\.person$/, '');
const rows = git('log', '--format=%H%x1f%aI%x1f%B%x1e').split('\x1e').map((r) => r.trim()).filter(Boolean).map((r) => {
  const [h, t, body] = r.split('\x1f');
  const m = /^Agent:\s*(\S+)/im.exec(body || '');
  return { h, t: new Date(t), role: m ? roleOf(m[1]) : '(no trailer)' };
});
rows.sort((a, b) => a.t - b.t);
const byRole = {};
for (const r of rows) byRole[r.role] = (byRole[r.role] || 0) + 1;
const shallow = git('rev-parse', '--is-shallow-repository').trim() === 'true';
const tags = git('tag', '--list', 'v*').split('\n').filter(Boolean);
const iso = (d) => d.toISOString().replace('.000Z', 'Z');
const mins = (a, b) => Math.round((b - a) / 60000);

// activity lines per agent
const act = {};
let actTotal = 0;
for (const f of readdirSync('team/activity').filter((f) => f.endsWith('.jsonl'))) {
  const n = readFileSync('team/activity/' + f, 'utf8').split('\n').filter((l) => l.trim()).length;
  act[f.replace('.jsonl', '')] = n; actTotal += n;
}

// costs
const costs = existsSync('team/costs.jsonl') ? readFileSync('team/costs.jsonl', 'utf8').split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l)) : [];
const cost = {};
for (const c of costs) {
  const k = roleOf(c.role);
  cost[k] ||= { runs: 0, usd: 0, failed: 0 };
  cost[k].runs++; cost[k].usd += c.cost_usd_api_equivalent || 0;
  if (/^failed|did not start|push failed/.test(c.note || '')) cost[k].failed++;
}
const byModel = {};
for (const c of costs) { byModel[c.model] ||= { runs: 0, usd: 0 }; byModel[c.model].runs++; byModel[c.model].usd += c.cost_usd_api_equivalent || 0; }
const usd = (x) => '$' + x.toFixed(2);

const liveLine = git('log', '--format=%h %aI %s', '--grep=v0.1.0 live').trim().split('\n').filter(Boolean).pop();
const live = liveLine ? { h: liveLine.split(' ')[0], t: new Date(liveLine.split(' ')[1]) } : null;
const first = rows[0], last = rows[rows.length - 1];
const tbl = (head, data) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...data.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const out = `# Case study numbers

Generated by case-study/count.mjs from \`git log\` (author times, trailer \`Agent:\`), \`git tag\`, \`team/activity/*.jsonl\` and \`team/costs.jsonl\`. Do not edit by hand: run \`node case-study/count.mjs --write\`. Times are UTC. Dollar figures are API-equivalent as recorded in team/costs.jsonl, not an invoice; the conductor's own session is not in that file.

${shallow ? 'WARNING: this clone is shallow, so the counts below are incomplete. Run `git fetch --unshallow` and count again.\n\n' : ''}Run on the history up to commit ${last.h.slice(0, 7)} (${iso(last.t)}).

## Totals
${tbl(['Number', 'Value', 'Source'], [
  ['Commits on this branch', String(rows.length), 'git log'],
  ['First commit in this history', iso(first.t), 'git log'],
  ['Latest commit', iso(last.t), 'git log'],
  ['Span, first to latest commit (minutes)', String(mins(first.t, last.t)), 'git log'],
  ...(live ? [['First commit to the commit that records v0.1.0 live (minutes)', String(mins(first.t, live.t)), `git log, commit ${live.h} (subject contains "v0.1.0 live")`]] : []),
  ['Version tags (CI sets one per deploy)', String(tags.length), 'git tag'],
  ['Activity-log lines', String(actTotal), 'team/activity/*.jsonl'],
  ['Recorded runs', String(costs.length), 'team/costs.jsonl'],
])}

## Commits per agent (by \`Agent:\` trailer)
${tbl(['Agent', 'Commits', 'Activity lines'], Object.entries(byRole).sort((a, b) => b[1] - a[1]).map(([r, n]) => [r, String(n), String(act[r] ?? 0)]))}

## Cost per role (API-equivalent dollars, from team/costs.jsonl)
${tbl(['Role', 'Recorded runs', 'Of which failed or not started', 'Dollars'], Object.entries(cost).sort((a, b) => b[1].usd - a[1].usd).map(([r, c]) => [r, String(c.runs), String(c.failed), usd(c.usd)]))}

## Cost per model
${tbl(['Model', 'Runs', 'Dollars', 'Dollars per run'], Object.entries(byModel).map(([m, c]) => [m, String(c.runs), usd(c.usd), usd(c.usd / c.runs)]))}

Caveats: runs are only counted once someone records them in team/costs.jsonl, so a run missing there is missing here. Failed runs are counted because they cost something. The model split follows Dinis's instruction of 2026-11-15 ~18:20 to run every agent but the conductor on Sonnet; whether it saved money cannot be read from these numbers until there are more Sonnet runs that finished.
`;
if (process.argv.includes('--write')) { writeFileSync('case-study/numbers.md', out); console.log('wrote case-study/numbers.md'); } else process.stdout.write(out);
